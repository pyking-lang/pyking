(** How the interpreter reaches a module implemented in a target
    language: through its OCaml implementation, compiled to a plugin and
    loaded into this executable with Dynlink. A compiled program links
    `<module>_external.ml` into itself; an interpreted one loads
    `<module>_external.cmxs`, built from that same file, so the
    interpreter runs everything the ocaml targets do without `pyk`
    being rebuilt for a new library. See docs/libraries.md, "How the
    interpreter reaches an OCaml implementation".

    A plugin is the implementation together with a registration file
    generated from the module's declarations, which records each
    declared name in `Pyk_plugin` when the plugin is loaded, and with
    `<module>_external_plugin.ml` between the two where the library has
    one. A value
    crosses the boundary by its declared type: nothing else says whether
    an immediate OCaml value is an Int, a Bool or unit.

    The plugin is found beside the implementation, where `make libs`
    writes the standard library's, and is used there when the digest
    written beside it is the digest of what it would be built from now.
    Otherwise it is compiled into a cache named by that digest, with
    `$OCAMLOPT` (or `ocamlopt`), which must be the OCaml this executable
    was built by.

    This module is in the executable rather than the library because it
    starts a process and loads code (see docs/build.md).

    Data structures:
      unit_ -- one external module: its name, its declared names and
        types, and where its declaration half is.

    Functions:
      shim name declared -- the registration file for a module.
      glue unit_ -- the file joining an implementation to the interpreter.
      digest unit_ -- what a module's plugin is built from, as a digest.
      build_plugin unit_ output -- compiles a module's plugin to output.
      load units -- loads every module's plugin, refusing one that
        cannot be built or loaded.
      externals units -- the interpreter's way into those modules.
      set_arguments program arguments -- what the program sees as its
        own argv. *)

open Syntax

(** One external module the interpreter has to reach. *)
type unit_ = {
  name : string;
  declared : (string * typ) list;
  declaration_path : string;
}

(* The same no-position info stdlib hosts use: a host operation is not
   written anywhere in the program. *)
let host_info =
  { Lexer.file = "<host>"; row1 = 1; col1 = 0; row2 = 1; col2 = 0 }

(** The position a refusal about a module's plugin points at: the first
    line of its declaration half. string -> info *)
let declaration_info path =
  { Lexer.file = path; row1 = 1; col1 = 0; row2 = 1; col2 = 0 }

(** Raises the Module_error a module whose plugin cannot be had is
    refused with. unit_ -> string -> 'a *)
let refuse (unit : unit_) message =
  raise (Module.Module_error (declaration_info unit.declaration_path, message))

(** Raises the Pyking runtime error for a value that does not fit the
    type it was declared with. string -> 'a *)
let trap message = raise (Interpreter.Trap (host_info, message))

(* --- files --- *)

(** The OCaml module a plugin's implementation is: the file's own name.
    string -> string *)
let implementation_module name = String.capitalize_ascii (name ^ "_external")

(** The implementation file beside a module's declaration half.
    unit_ -> string *)
let implementation (unit : unit_) =
  Filename.concat (Filename.dirname unit.declaration_path) (unit.name ^ "_external.ml")

(** The file a module's implementation may have beside it to join it to
    the interpreter: compiled into the plugin after the implementation,
    and the one place the implementation may name Pyk_plugin.
    unit_ -> string *)
let glue (unit : unit_) =
  Filename.concat (Filename.dirname unit.declaration_path) (unit.name ^ "_external_plugin.ml")

(** The plugin `make libs` writes beside an implementation.
    unit_ -> string *)
let prebuilt (unit : unit_) = Filename.remove_extension (implementation unit) ^ ".cmxs"

(** Where the digest of what a plugin was built from is written beside
    it. string -> string *)
let digest_path plugin = Filename.remove_extension plugin ^ ".digest"

(** The registration file for a module: one `Pyk_plugin.register` per
    declared name, public or not, since the module's Pyking half may
    call a private one. string -> [(string, typ)] -> string *)
let shim name declared =
  let owner = implementation_module name in
  String.concat "\n"
    ([
       Printf.sprintf
         "(* Generated by pyk from %s_external.pyk: registers each name it \
          declares. *)"
         name;
       "let () =";
     ]
    @ List.map
        (fun (field, _) ->
          Printf.sprintf "  Pyk_plugin.register %S %S (Obj.repr %s.%s);" name field owner
            field)
        declared
    @ [ "  ()"; "" ])

(** The directory holding pyk_plugin.cmi, which a plugin is compiled
    against: share/plugin beside the executable, where `make` puts it
    and a package ships it. () -> string *)
let interface_directory () =
  Filename.concat (Filename.concat (Install.root ()) "share") "plugin"

(** Where a plugin compiled on demand is kept: pyking/plugins under the
    user's cache directory. () -> string *)
let cache_directory () =
  let base =
    match Sys.getenv_opt "XDG_CACHE_HOME" with
    | Some directory when directory <> "" -> directory
    | _ -> (
        match Sys.getenv_opt (if Sys.win32 then "LOCALAPPDATA" else "HOME") with
        | Some home when Sys.win32 -> home
        | Some home -> Filename.concat home ".cache"
        | None -> Filename.get_temp_dir_name ())
  in
  Filename.concat (Filename.concat base "pyking") "plugins"

(** Makes a directory and every missing parent. string -> () *)
let rec make_directory path =
  if not (Sys.file_exists path) then (
    make_directory (Filename.dirname path);
    try Sys.mkdir path 0o755 with Sys_error _ when Sys.file_exists path -> ())

(* --- compiling --- *)

(** The command that compiles OCaml: `$OCAMLOPT` split on spaces, the
    variable the rest of the toolchain reads, or `ocamlopt`.
    () -> [string] *)
let compiler () =
  match Sys.getenv_opt "OCAMLOPT" with
  | Some command when String.trim command <> "" ->
      List.filter (fun word -> word <> "") (String.split_on_char ' ' command)
  | _ -> [ "ocamlopt" ]

(** Runs a command with its output in a file, answering the exit status
    and what it wrote. [string] -> string -> (int, string) *)
let run_logged command log =
  let quoted = String.concat " " (List.map Filename.quote command) in
  let status =
    Sys.command (Printf.sprintf "%s > %s 2>&1" quoted (Filename.quote log))
  in
  let text = try Module.read_whole_file log with Sys_error _ -> "" in
  (status, String.trim text)

(** The version the compiler reports, or None where it cannot be run.
    string -> string option *)
let compiler_version scratch =
  let status, text =
    run_logged (compiler () @ [ "-version" ]) (Filename.concat scratch "version")
  in
  if status = 0 then Some text else None

(** The OCaml this executable was built by, without a `+` suffix a
    development build carries. string *)
let own_version =
  match String.index_opt Sys.ocaml_version '+' with
  | Some at -> String.sub Sys.ocaml_version 0 at
  | None -> Sys.ocaml_version

(** What a module's plugin is built from, as one digest: the OCaml
    implementation, its registration file, the OCaml and pyk versions and
    the interface the plugin is compiled against. A plugin whose digest
    is this is the plugin this executable would build now.
    unit_ -> string *)
let digest (unit : unit_) =
  let interface = Filename.concat (interface_directory ()) "pyk_plugin.cmi" in
  Digest.to_hex
    (Digest.string
       (String.concat "\000"
          [
            own_version;
            Version.version;
            Module.read_whole_file (implementation unit);
            (if Sys.file_exists (glue unit) then Module.read_whole_file (glue unit) else "");
            shim unit.name unit.declared;
            (if Sys.file_exists interface then Digest.to_hex (Digest.file interface) else "");
          ]))

(** Whether the plugin at path was built from what `digest` says, by the
    digest written beside it. string -> string -> bool *)
let built_from path expected =
  Sys.file_exists path
  && (try String.trim (Module.read_whole_file (digest_path path)) = expected
      with Sys_error _ -> false)

(** Compiles a module's implementation and its registration file into a
    plugin at output, in a scratch directory of its own, and writes its
    digest beside it. Raises Module_error where there is no OCaml
    compiler of the right version or the implementation does not
    compile. unit_ -> string -> () *)
let build_plugin (unit : unit_) output =
  let scratch = Filename.temp_dir "pyk-plugin" "" in
  let tool = String.concat " " (compiler ()) in
  (match compiler_version scratch with
  | None ->
      refuse unit
        (Printf.sprintf
           "'%s' is implemented in OCaml, and running it needs its plugin, \
            which is compiled with '%s' -- and that could not be run. \
            Install OCaml %s, or set $OCAMLOPT"
           unit.name tool own_version)
  | Some version when version <> own_version ->
      refuse unit
        (Printf.sprintf
           "'%s' is implemented in OCaml, and its plugin has to be compiled \
            by OCaml %s, the version pyk was built by; '%s' is %s"
           unit.name own_version tool version)
  | Some _ -> ());
  let source = implementation unit in
  let copied = Filename.concat scratch (Filename.basename source) in
  let shim_file = Filename.concat scratch (unit.name ^ "_external_register.ml") in
  let write path text =
    let channel = open_out_bin path in
    output_string channel text;
    close_out channel
  in
  write copied (Module.read_whole_file source);
  let glued =
    if Sys.file_exists (glue unit) then (
      let path = Filename.concat scratch (Filename.basename (glue unit)) in
      write path (Module.read_whole_file (glue unit));
      [ path ])
    else []
  in
  write shim_file (shim unit.name unit.declared);
  let built = Filename.concat scratch (unit.name ^ "_external.cmxs") in
  let status, text =
    run_logged
      (compiler ()
      @ [
          "-shared";
          (* Not the directory pyk runs in, where a program may have
             been compiled with a module of the same name. *)
          "-nocwd";
          "-I";
          "+unix";
          "-I";
          interface_directory ();
          "-I";
          scratch;
          "-o";
          built;
          copied;
        ]
      @ glued @ [ shim_file ])
      (Filename.concat scratch "log")
  in
  if status <> 0 then
    refuse unit
      (Printf.sprintf "the OCaml implementation of '%s' does not compile: %s"
         unit.name text);
  make_directory (Filename.dirname output);
  (* Written beside the destination and renamed onto it, so another run
     reading the cache never sees half a plugin. *)
  let partial = output ^ ".partial" in
  write partial (Module.read_whole_file built);
  Sys.rename partial output;
  write (digest_path output) (digest unit ^ "\n")

(* --- loading --- *)

(** Loads one plugin file, answering the loader's refusal as text rather
    than raising it. A plugin already loaded is not a refusal: the
    registrations it made are still there. string -> string option *)
let load_file path =
  try
    Dynlink.loadfile path;
    None
  with Dynlink.Error (Dynlink.Module_already_loaded _) -> None
  | Dynlink.Error error -> Some (Dynlink.error_message error)

(** Whether a module's plugin is registered already, which is what
    loading it would have done. unit_ -> bool *)
let registered (unit : unit_) =
  match unit.declared with
  | [] -> true
  | (field, _) :: _ -> Pyk_plugin.find unit.name field <> None

(** Loads one module's plugin: the one beside its implementation where
    that was built from what it would be built from now and loads, else
    one compiled into the cache. unit_ -> () *)
let load_one (unit : unit_) =
  let source = implementation unit in
  Pyk_plugin.set_directory unit.name (Filename.dirname unit.declaration_path);
  if registered unit then ()
  else if not (Sys.file_exists source) then
    refuse unit
      (Printf.sprintf
         "'%s' is implemented in a target language, and the interpreter \
          runs its OCaml implementation -- but there is no file '%s'"
         unit.name source)
  else
    let expected = digest unit in
    let beside = prebuilt unit in
    let refused =
      if built_from beside expected then load_file beside else Some ""
    in
    match refused with
    | None -> ()
    | Some first ->
        let cached = Filename.concat (cache_directory ()) (expected ^ ".cmxs") in
        if not (built_from cached expected) then build_plugin unit cached;
        (match load_file cached with
        | None -> ()
        | Some error ->
            refuse unit
              (Printf.sprintf "the plugin for '%s' cannot be loaded: %s%s"
                 unit.name error
                 (if first = "" then "" else " (and the one beside it: " ^ first ^ ")")))

(** Loads the plugin of every module given, in order. Raises
    Module_error for the first that cannot be had. [unit_] -> () *)
let load units = List.iter load_one units

(* --- values across the boundary --- *)

(** A Pyking value as the OCaml value its declared type says it is. A
    function becomes a curried OCaml function that calls it back through
    back. (value -> [value] -> value) -> typ -> Interpreter.value -> Obj.t *)
let rec to_host back type_ value =
  match (type_, value) with
  | TFunction (_, params, _, _, _, _, _),
    (Interpreter.VClosure _ | Interpreter.VBuiltin _ | Interpreter.VHostFun _) ->
      let rec curried types got =
        match types with
        | [] ->
            ignore (back value (List.rev got));
            Obj.repr ()
        | t :: rest -> Obj.repr (fun (a : Obj.t) -> curried rest (of_host t a :: got))
      in
      if params = [] then Obj.repr (fun () -> ignore (back value []))
      else curried params []
  | TInt _, Interpreter.VInt n -> Obj.repr n
  | TFloat _, Interpreter.VFloat x -> Obj.repr x
  | TString _, Interpreter.VString text -> Obj.repr text
  | TBool _, Interpreter.VBool b -> Obj.repr b
  | TTuple (_, [], _), _ -> Obj.repr ()
  | TList (_, element, _), Interpreter.VList items ->
      Obj.repr (List.map (to_host back element) items)
  | TTuple (_, types, _), Interpreter.VTuple items
    when List.length types = List.length items ->
      let block = Obj.new_block 0 (List.length items) in
      List.iteri
        (fun index (t, item) -> Obj.set_field block index (to_host back t item))
        (List.combine types items);
      block
  | _ ->
      trap
        (Printf.sprintf "%s cannot be passed where %s is declared"
           (Interpreter.describe value)
           (pprint_type default_config type_))

(** An OCaml value as the Pyking value its declared type says it is.
    typ -> Obj.t -> Interpreter.value *)
and of_host type_ value =
  match type_ with
  | TInt _ -> Interpreter.VInt (Obj.obj value : int)
  | TFloat _ -> Interpreter.VFloat (Obj.obj value : float)
  | TString _ -> Interpreter.VString (Obj.obj value : string)
  | TBool _ -> Interpreter.VBool (Obj.obj value : bool)
  | TTuple (_, [], _) -> Interpreter.VUnit
  | TList (_, element, _) ->
      Interpreter.VList (List.map (of_host element) (Obj.obj value : Obj.t list))
  | TTuple (_, types, _) ->
      Interpreter.VTuple (List.mapi (fun index t -> of_host t (Obj.field value index)) types)
  | _ ->
      trap
        (Printf.sprintf "a value of type %s cannot come back from OCaml"
           (pprint_type default_config type_))

(** Applies an OCaml function to its arguments one at a time -- a curried
    function takes them that way whatever its arity -- or to unit where
    it takes none. Obj.t -> [Obj.t] -> Obj.t *)
let apply_host f args =
  match args with
  | [] -> (Obj.obj f : unit -> Obj.t) ()
  | args -> List.fold_left (fun f a -> (Obj.obj f : Obj.t -> Obj.t) a) f args

(** The interpreter's way into every module given, whose plugins `load`
    has loaded. [unit_] -> Interpreter.externals *)
let externals units =
  let declared module_ field =
    match List.find_opt (fun (unit : unit_) -> unit.name = module_) units with
    | None -> None
    | Some unit -> List.assoc_opt field unit.declared
  in
  let implementation module_ field =
    match Pyk_plugin.find module_ field with
    | Some value -> value
    | None ->
        trap
          (Printf.sprintf "'%s.%s' has no OCaml implementation loaded" module_ field)
  in
  Interpreter.
    {
      field =
        (fun module_ field ->
          match declared module_ field with
          | Some type_ -> of_host type_ (implementation module_ field)
          | None -> trap (Printf.sprintf "'%s.%s' is not declared" module_ field));
      call =
        (fun back module_ field args ->
          match declared module_ field with
          | Some (TFunction (_, params, result, _, _, _, _)) ->
              (* A call with no arguments arrives with none, or with the
                 unit a `()` argument list is. *)
              let args = if params = [] then [] else args in
              if List.length args <> List.length params then
                trap
                  (Printf.sprintf "'%s.%s' takes %d argument(s), not %d" module_
                     field (List.length params) (List.length args));
              (* An implementation refuses a call by failing: that is a
                 Pyking runtime error here, with the implementation's
                 own words. *)
              of_host result
                (try apply_host (implementation module_ field) (List.map2 (to_host back) params args)
                 with Failure message -> trap message)
          | _ -> trap (Printf.sprintf "'%s.%s' is not a function" module_ field));
    }

(* --- the program's own arguments --- *)

external modify_argv : string array -> unit = "caml_sys_modify_argv"

(** Makes `Sys.argv` what the program would have been started with --
    its own file, then its own arguments -- since an implementation
    such as sys_external.ml reads the arguments from there.
    string -> [string] -> () *)
let set_arguments program arguments =
  modify_argv (Array.of_list (program :: arguments))
